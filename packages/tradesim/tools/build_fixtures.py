"""Emit the golden fixture pack as JSON.

Every expected value in this file is a hand-computed literal. Nothing here calls the
engine. That is the whole point: a fixture generated by the engine it grades proves only
that the engine is self-consistent.

The arithmetic behind each number is written out in the comment above it so a reader can
check it without running anything. The standing test instrument keeps the arithmetic
trivial:

    tick 0.01, qty step 0.001, taker 0.001 (0.1%), maker 0.0004 (0.04%), qty 1.0,
    entry fill 100.00, starting equity 10 000, 1-minute bars,
    bar 0 ts 0, bar 1 ts 60 000, bar 2 ts 120 000, bar 3 ts 180 000.

Isolated liquidation for a long solves ``equity(P) == maintenance_margin(P)``:

    P_liq = (qty*entry - margin - deduction) / (qty * (1 - mm_rate - close_fee_rate))

At leverage 10 the margin is 10, so P_liq = (100 - 10) / (1 - 0.005 - 0.001)
                                          = 90 / 0.994 = 90.5432...  -> 90.55 (ceil to tick, adverse).
At leverage 50 the margin is 2,  so P_liq = 98 / 0.994 = 98.5915...  -> 98.60.
At leverage  2 the margin is 50, so P_liq = 50 / 0.994 = 50.3018...  -> 50.31.

Run with:  python tools/build_fixtures.py
"""

