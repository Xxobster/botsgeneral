def fixture(
    ids: list[str],
    title: str,
    *,
    bars: list[list[float]],
    signals: list[dict[str, Any]],
    expect: dict[str, Any],
    instrument: dict[str, Any] | None = None,
    costs: dict[str, Any] | None = None,
    margin: dict[str, Any] | None = None,
    sizing: dict[str, Any] | None = None,
    sim: dict[str, Any] | None = None,
    touch_bars: dict[str, Any] | None = None,
    funding: list[list[float]] | None = None,
    kind: str = "simulation",
    rationale: str = "",
) -> dict[str, Any]:
    return {
        "ids": ids,
        "kind": kind,
        "title": title,
        "rationale": rationale,
        "instrument": {**INSTRUMENT, **(instrument or {})},
        "costs": {**COSTS, **(costs or {})},
        "margin": {**MARGIN_L10, **(margin or {})},
        "sizing": {**SIZING_Q1, **(sizing or {})},
        "sim": {**SIM, **(sim or {})},
        "bars": {"timeframe_ms": TF, "rows": bars},
        "touch_bars": touch_bars,
        "funding": funding or [],
        "signals": signals,
        "expect": expect,
        "tolerance": 1e-9,
    }


