def metric_fixture(
    ids: list[str], title: str, inputs: dict[str, Any], expect: dict[str, Any]
) -> dict[str, Any]:
    """A metric graded on its own arithmetic, with no simulation in the way."""
    return {
        "ids": ids,
        "kind": "metrics",
        "title": title,
        "rationale": "",
        **inputs,
        "expect": {"metrics": expect},
        "tolerance": 1e-9,
    }


def _metric_fixtures() -> dict[str, dict[str, Any]]:
    f: dict[str, dict[str, Any]] = {}

    # ================================================================== METR-001 ======
    # Fold A is +10 against -5 (ratio 2.00); fold B is +1 against -10 (ratio 0.10). The
    # mean of the ratios is 1.05 and reads as profitable. Pooled: 11 / 15 = 0.733333...
    f["METR-001_profit_factor_is_pooled"] = metric_fixture(
        ["METR-001"],
        "Profit factor pools the trades instead of averaging the folds",
        {"pnls": [10.0, -5.0, 1.0, -10.0]},
        {
            "profit_factor": 11.0 / 15.0,
            "profit_factor_note": "",
            # 2 wins in 4 = 50%, Wilson 95%: 0.150,  0.850  (symmetric at p = 0.5)
            "win_rate": 0.5,
        },
    )

    # An uncapped ratio: 1000 / 0.01 = 100000. No sentinel ceiling.
    f["METR-001_profit_factor_is_uncapped"] = metric_fixture(
        ["METR-001"],
        "A large profit factor is reported, not clipped to a tidy ceiling",
        {"pnls": [1000.0, -0.01]},
        {"profit_factor": 100_000.0},
    )

    # ================================================================== METR-002 ======
    # Wilson score interval for 3 wins in 3, z = 1.96, written out from the formula:
    #   centre = (phat + z^2/2n) / (1 + z^2/n)
    #   margin = (z / (1 + z^2/n)) * sqrt(phat(1-phat)/n + z^2/4n^2)
    z, wins, trials = 1.96, 3, 3
    phat = wins / trials
    denom = 1.0 + z * z / trials
    centre = (phat + z * z / (2 * trials)) / denom
    margin = (z / denom) * (
        (phat * (1.0 - phat) / trials + z * z / (4 * trials * trials)) ** 0.5
    )
    f["METR-002_zero_gross_loss_is_infinite"] = metric_fixture(
        ["METR-002"],
        "Zero gross loss is infinity with a sample warning, never an automatic pass",
        {"pnls": [1.0, 2.0, 3.0]},
        {
            "profit_factor": "inf",
            "profit_factor_note": "insufficient-sample warning",
            "win_rate": 1.0,
            # Three winners do not establish a 100% win rate: the 95% interval starts
            # below 0.44, which is the whole reason a bare win rate is never quotable.
            "win_rate_ci_low": max(0.0, centre - margin),
            "win_rate_ci_high": min(1.0, centre + margin),
        },
    )

    # ================================================================== METR-003 ======
    # Peak 120 to trough 90 is 30, which is 25% of the peak, and the curve spends two
    # observations below the peak before recovering.
    f["METR-003_drawdown_on_the_equity_curve"] = metric_fixture(
        ["METR-003"],
        "Drawdown is measured peak to trough on the mark-to-market curve",
        {"equity": [100.0, 120.0, 90.0, 95.0, 130.0]},
        {"max_drawdown": 30.0, "max_drawdown_pct": 0.25, "max_drawdown_periods": 2},
    )

    # ================================================================== METR-004 ======
    # r = [0.01, -0.01, 0.02, 0.00]
    #   mean = 0.005
    #   deviations       = [0.005, -0.015, 0.015, -0.005]
    #   sum of squares   = 2.5e-05 + 2.25e-04 + 2.25e-04 + 2.5e-05 = 5.0e-04
    #   sample variance  = 5.0e-04 / 3 = 1.6666666666666666e-04
    #   sample std       = 0.012909944487358056
    #   raw Sharpe       = 0.005 / 0.012909944487358056 = 0.3872983346207417
    #   annualised       = raw * sqrt(365) = 0.3872983346207417 * 19.10497317454279
    #                    = 7.399338... (see the literal below)
    RAW_SHARPE = 0.005 / ((5.0e-04 / 3.0) ** 0.5)
    f["METR-004_raw_and_annualised_sharpe"] = metric_fixture(
        ["METR-004"],
        "Raw periodic and annualised Sharpe are separate numbers with a stated factor",
        {"returns": [0.01, -0.01, 0.02, 0.0], "annualisation_days": 365.0},
        {
            "sharpe.raw_periodic": RAW_SHARPE,
            "sharpe.annualisation_factor": 365.0**0.5,
            "sharpe.annualised": RAW_SHARPE * (365.0**0.5),
            "sharpe.n_periods": 4,
            "sharpe.available": True,
        },
    )

    f["METR-004_sharpe_undefined_on_a_flat_curve"] = metric_fixture(
        ["METR-004"],
        "Zero dispersion makes Sharpe undefined, not infinite and not zero",
        {"returns": [0.01, 0.01, 0.01]},
        {
            "sharpe.raw_periodic": "nan",
            "sharpe.available": False,
            "sharpe.reason": "zero return dispersion",
        },
    )

    # ================================================================== METR-005 ======
    # Bartlett-kernel long-run variance at truncation lag L = max(1, floor(4*(n/100)^(2/9))).
    # For n = 12: (0.12)^(2/9) = 0.62428..., 4 * that = 2.497..., so L = 2.
    #
    #   gamma_k = (1/n) * sum_t (x_t - xbar)(x_{t+k} - xbar)
    #   lrv     = gamma_0 + 2 * sum_{k=1..L} (1 - k/(L+1)) * gamma_k
    #   HAC Sharpe = mean / sqrt(lrv)
    #
    # The series below is deliberately positively autocorrelated (three up, three down,
    # repeating), so the long-run variance exceeds gamma_0 and the HAC value is BELOW the
    # IID one. The expected numbers are computed here from that formula directly, not by
    # calling the engine.
    series = [0.02, 0.015, 0.01, -0.01, -0.015, -0.005, 0.02, 0.018, 0.012, -0.012, -0.014, -0.006]
    n = len(series)
    mean = sum(series) / n
    dev = [x - mean for x in series]
    gamma0 = sum(d * d for d in dev) / n
    lag = 2
    lrv = gamma0
    for k in range(1, lag + 1):
        weight = 1.0 - k / (lag + 1.0)
        gamma_k = sum(dev[t] * dev[t - k] for t in range(k, n)) / n
        lrv += 2.0 * weight * gamma_k
    variance = sum(d * d for d in dev) / (n - 1)
    f["METR-005_hac_sharpe_alongside_iid"] = metric_fixture(
        ["METR-005"],
        "A serial-dependence-aware Sharpe is reported next to the IID value",
        {"returns": series, "annualisation_days": 365.0},
        {
            "sharpe.hac_lag": lag,
            "sharpe.raw_periodic": mean / (variance**0.5),
            "sharpe.hac_raw": mean / (lrv**0.5),
            "sharpe.hac_annualised": (mean / (lrv**0.5)) * (365.0**0.5),
        },
    )

    return f


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for existing in OUT_DIR.glob("*.json"):
        existing.unlink()
    fixtures = build()
    for name, payload in sorted(fixtures.items()):
        path = OUT_DIR / f"{name}.json"
        path.write_text(json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {len(fixtures)} fixtures to {OUT_DIR}")


if __name__ == "__main__":
    main()
